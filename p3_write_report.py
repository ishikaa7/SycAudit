a("| annotators disagree materially (>30%) | the F2 definition is still underdetermined; add worked examples and run a second round before choosing |")
a("| F5 still nests inside F2 | the facets are not separable as scored; escalate the five-facet objective question |")
a("| F2 and F5 come apart | keep both; adopt A or B and proceed to matched-pair kappa |")
a("")
a("### 8.4 Deliberately out of scope")
a("")
a("- No new large batch. 50 records, 2 annotators.")
a("- No modification of the existing 50 labels. The baseline is the comparison target,")
a("  not the thing being corrected.")
a("- No LLM inference. Phase 2's separate recommendation to LLM-score the gold 50")
