a("| protocol | each annotator also assigns a one-line justification for every F2>0, so category-boundary failures are diagnosable rather than guessed at |")
a("| adjudication | third reviewer resolves every annotator-vs-baseline and annotator-vs-annotator disagreement, recording which rubric clause was ambiguous |")
